#!/usr/bin/env node
/**
 * Writes src/lib/seo/revisions.generated.ts from git history.
 *
 * The dates in that file become <lastmod> in the sitemap and dateModified in
 * the JSON-LD. They used to be a hand-typed constant called TODAY, which is a
 * name that promises the opposite of what it did: it sat at one date for weeks
 * while the pages it described kept changing, so the site told crawlers its
 * content was staler than it was.
 *
 * Per-page granularity is not available, because one file holds the copy for
 * many pages. What is available is per-source-file granularity, which is the
 * real unit of change here: the marketing and legal copy lives in content.ts,
 * the tool copy in toolsContent.ts and toolsPages.ts, and the titles and
 * descriptions for both in site.ts. Two dates, each true.
 *
 * The generated file is committed. This script only ever overwrites it when it
 * can see enough history to be right: on a shallow clone every file reports the
 * HEAD commit, which would stamp today's date on every page at every deploy and
 * be a worse lie than the frozen constant was. In that case the committed value
 * stands, so a Vercel build reuses whatever the last full checkout worked out.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/lib/seo/revisions.generated.ts');

/** Each exported constant, and the sources whose last change it reports. */
const GROUPS = {
  CONTENT_REVISED: ['src/lib/seo/content.ts', 'src/lib/seo/site.ts'],
  TOOLS_REVISED: ['src/lib/seo/toolsContent.ts', 'src/lib/seo/toolsPages.ts', 'src/lib/seo/site.ts'],
};

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
}

/** True when git can answer "when did this file last change" honestly. */
function historyIsUsable() {
  try {
    if (git(['rev-parse', '--is-shallow-repository']) === 'true') return false;
    // More than one commit reachable means %cs per file is meaningful.
    return Number(git(['rev-list', '--count', 'HEAD'])) > 1;
  } catch {
    return false;
  }
}

/** ISO date (YYYY-MM-DD) of the newest commit touching any of `files`. */
function lastChanged(files) {
  const dates = files
    .map((f) => {
      try {
        return git(['log', '-1', '--format=%cs', '--', f]);
      } catch {
        return '';
      }
    })
    .filter(Boolean);
  return dates.sort().pop() ?? '';
}

if (!historyIsUsable()) {
  console.log('gen-revisions: shallow or absent git history, keeping committed dates');
  process.exit(0);
}

const resolved = Object.fromEntries(
  Object.entries(GROUPS).map(([name, files]) => [name, lastChanged(files)]),
);

const missing = Object.entries(resolved).filter(([, date]) => !date);
if (missing.length > 0) {
  console.log(`gen-revisions: no history for ${missing.map(([n]) => n).join(', ')}, keeping committed dates`);
  process.exit(0);
}

const body = `/**
 * Generated by scripts/gen-revisions.mjs. Do not edit by hand.
 *
 * The last date on which each group of content sources actually changed, used
 * as <lastmod> in the sitemap and dateModified in the JSON-LD.
 */

/** Marketing, audience, reference and legal copy: src/lib/seo/content.ts. */
export const CONTENT_REVISED = '${resolved.CONTENT_REVISED}';

/** The typing tools: src/lib/seo/toolsContent.ts and toolsPages.ts. */
export const TOOLS_REVISED = '${resolved.TOOLS_REVISED}';
`;

const previous = (() => {
  try {
    return readFileSync(OUT, 'utf8');
  } catch {
    return '';
  }
})();

if (previous === body) {
  console.log(`gen-revisions: unchanged (content ${resolved.CONTENT_REVISED}, tools ${resolved.TOOLS_REVISED})`);
} else {
  writeFileSync(OUT, body);
  console.log(`gen-revisions: content ${resolved.CONTENT_REVISED}, tools ${resolved.TOOLS_REVISED}`);
}
